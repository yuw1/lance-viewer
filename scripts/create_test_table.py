#!/usr/bin/env python3
"""
Create the demo dataset for the viewer (with full indexes).

Usage:
    python scripts/create_test_table.py              # default: examples/demo.lance, 5000 rows
    python scripts/create_test_table.py --rows 1000

Output: examples/demo.lance   (examples/ is gitignored, not committed)

Deps: pylance + pyarrow
    uv pip install pylance pyarrow
"""
import argparse
import os
import random
import shutil

import lance
import pyarrow as pa

# Auto-register into SQLite after building, so the viewer sidebar sees it directly
from lance_viewer.dataset_store import get_store

DEFAULT_ROWS = 5000
DEFAULT_VEC_DIM = 128
OUT = os.path.abspath("examples/demo.lance")


def build_table(n, vec_dim):
    """Build a demo data table with n rows and vec_dim-dimensional vectors."""
    ids = list(range(n))
    names = [f"item_{i:04d}" for i in range(n)]
    descs = [f"This is test description {i}, for full-text index demo keyword{i%50} topic{chr(97+i%26)}" for i in range(n)]
    scores = [i % 100 * 1.0 for i in range(n)]
    # Cluster the vectors so the vector index is meaningful (10 clusters)
    random.seed(42)
    vecs = []
    for i in range(n):
        cluster = i // 500
        center = [cluster * 0.1] * vec_dim
        v = [center[d] + random.gauss(0, 0.05) for d in range(vec_dim)]
        vecs.append(v)
    return pa.table({
        "id": pa.array(ids, type=pa.int64()),
        "name": pa.array(names, type=pa.string()),
        "description": pa.array(descs, type=pa.string()),
        "score": pa.array(scores, type=pa.float64()),
        "vector": pa.array(vecs, type=pa.list_(pa.float32(), vec_dim)),
    })


def build_indexes(ds):
    """Build the full index set: BTree(id/score) + Inverted(name) + FTS(description) + Vector(IVF_HNSW_FLAT)."""
    print("Building indexes...")
    ds.create_scalar_index("id", index_type="BTREE", name="idx_id")
    print("  idx_id (BTREE) OK")
    ds.create_scalar_index("score", index_type="BTREE", name="idx_score")
    print("  idx_score (BTREE) OK")
    ds.create_scalar_index("name", index_type="INVERTED", name="idx_name")
    print("  idx_name (INVERTED) OK")
    ds.create_scalar_index("description", index_type="FTS", name="idx_fts")
    print("  idx_fts (FTS) OK")
    ds.create_index("vector", index_type="IVF_HNSW_FLAT", name="idx_hnsw",
                    metric="cosine",
                    params={"M": 16, "ef_construction": 100, "ef": 50,
                            "num_partitions": 10, "num_sub_vectors": 16})
    print("  idx_hnsw (IVF_HNSW_FLAT) OK")


def create_refs(ds):
    """Create the demo branch (feature-x) and tag (snapshot-v3) that tests/repo expect."""
    latest = len(ds.versions())
    ds.tags.create("snapshot-v3", reference=3)
    ds.create_branch("feature-x", reference=latest)
    print(f"  refs: tag snapshot-v3 (v3) + branch feature-x (v{latest}) OK")


def register(name, path, note=""):
    """Register the dataset into the SQLite registry (updates if it exists) so the viewer sidebar sees it."""
    row = get_store().add(name, path, note)
    print(f"  Registered: id={row['id']} name={row['name']} path={row['path']}")


def main():
    ap = argparse.ArgumentParser(description="Create the viewer demo dataset examples/demo.lance")
    ap.add_argument("--rows", type=int, default=DEFAULT_ROWS, help="number of rows (default 5000)")
    ap.add_argument("--vec-dim", type=int, default=DEFAULT_VEC_DIM, help="vector dimension (default 128)")
    ap.add_argument("--no-register", action="store_true", help="only build the table, skip SQLite registration")
    args = ap.parse_args()

    table = build_table(args.rows, args.vec_dim)
    if os.path.exists(OUT):
        shutil.rmtree(OUT)

    print(f"Creating dataset: {OUT}")
    ds = lance.write_dataset(table, OUT, mode="overwrite")
    print(f"  Wrote {ds.count_rows()} rows, {len(table.column_names)} columns")
    build_indexes(ds)
    create_refs(ds)

    if not args.no_register:
        register("Demo index table", "examples/demo.lance", note="Demo dataset (generated by scripts/create_test_table.py)")
    print("=== Done ===")


if __name__ == "__main__":
    main()
